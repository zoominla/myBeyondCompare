#!/usr/bin/env python3
"""Inline web/*.css and web/*.js into web/index.html and emit src/gui_page.cpp."""
import os, sys
here = os.path.dirname(os.path.abspath(__file__))
web = os.path.join(here, 'web')
order = ['util', 'i18n', 'tabs', 'dir', 'text', 'hex', 'merge', 'home', 'main']
rd = lambda p: open(os.path.join(web, p), encoding='utf8').read()
html = rd('index.html')
css = rd('style.css')
js = '\n'.join(rd(n + '.js') for n in order)
assert '</script' not in js.lower()
page = html.replace('/*__CSS__*/', css).replace('/*__JS__*/', js)
assert '__MBC_TOKEN__' in page
if len(sys.argv) > 1 and sys.argv[1] == '--html':
    open(os.path.join(here, 'tests', 'page.html'), 'w', encoding='utf8').write(page)
data = page.encode('utf8')
chunks, i = [], 0
while i < len(data):
    j = min(len(data), i + 6000)
    while j < len(data) and (data[j] & 0xC0) == 0x80:  # don't split inside a UTF-8 sequence
        j -= 1
    chunks.append(data[i:j].decode('utf8'))
    i = j
out = ['// GENERATED by embed.py from web/ - do not edit', '#include <string>', '#include "gui.h"', '',
       'namespace bc {', 'const char* guiPageHtml() {', '  static const std::string page = std::string()']
for c in chunks:
    assert ')MBCX"' not in c
    out.append('      + R"MBCX(' + c + ')MBCX"')
out.append('      ;')
out.append('  return page.c_str();')
out.append('}')
out.append('}  // namespace bc')
open(os.path.join(here, 'src', 'gui_page.cpp'), 'w', encoding='utf8', newline='\n').write('\n'.join(out) + '\n')
print('page bytes', len(data), 'chunks', len(chunks))
